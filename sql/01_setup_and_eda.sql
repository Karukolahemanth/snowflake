  COMMENT = 'Schema for all phishing ML pipeline objects';

USE SCHEMA PHISHING_SCHEMA;

DROP TABLE IF EXISTS RAW_EMAILS;

CREATE OR REPLACE TABLE RAW_EMAILS (
    EMAIL_ID          INTEGER,
    SENDER            VARCHAR(200),
    SENDER_DOMAIN     VARCHAR(200),
    SUBJECT           VARCHAR(500),
    BODY              TEXT,
    HAS_URL           INTEGER,         -- 1 = has URL, 0 = no URL
    URL_COUNT         INTEGER,         -- Number of URLs in email
    HAS_IP_URL        INTEGER,         -- 1 = URL contains IP address
    URL_LENGTH        INTEGER,         -- Average URL length
    HAS_URGENT_WORDS  INTEGER,         -- 1 = contains urgency keywords
    HTML_TAGS_COUNT   INTEGER,         -- Number of HTML tags
    NUM_SPECIAL_CHARS INTEGER,         -- Count of special characters
    WORD_COUNT        INTEGER,         -- Total word count in body
    SUBJECT_LENGTH    INTEGER,         -- Character length of subject
    SENDER_NAME_MISMATCH INTEGER,      -- 1 = display name != domain
    HAS_ATTACHMENT    INTEGER,         -- 1 = has attachment
    REPLY_TO_DIFFERENT INTEGER,        -- 1 = reply-to != sender
    SPF_PASS          INTEGER,         -- 1 = SPF authentication passed
    DKIM_PASS         INTEGER,         -- 1 = DKIM authentication passed
    LABEL             INTEGER          -- 1 = Phishing, 0 = Legitimate
);

